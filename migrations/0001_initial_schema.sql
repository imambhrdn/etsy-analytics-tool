create table if not exists shops (
  id uuid primary key default gen_random_uuid(),
  etsy_shop_id bigint unique,
  name text,
  url text,
  is_own_shop boolean not null default false,
  tracking_enabled boolean not null default false,
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  raw_data jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists shops_etsy_shop_id_idx on shops (etsy_shop_id);
create index if not exists shops_is_own_shop_idx on shops (is_own_shop);

